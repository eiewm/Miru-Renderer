pub(crate) fn generated_mod_icon_record(acronym: &str) -> Option<&'static GeneratedModIconRecord> {
    let normalized = acronym.trim().to_ascii_uppercase();
    GENERATED_MOD_ICON_RECORDS
        .iter()
        .find(|record| record.acronym.eq_ignore_ascii_case(&normalized))
}
pub(crate) fn generated_mod_icon_is_excluded(acronym: &str) -> bool {
    let normalized = acronym.trim().to_ascii_uppercase();
    GENERATED_MOD_ICON_EXCLUDED_ACRONYMS
        .iter()
        .any(|excluded| excluded.eq_ignore_ascii_case(&normalized))
}
